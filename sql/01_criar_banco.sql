-- CRIACAO DO MODELO DIMENSIONAL NO POSTGRESQL
-- ============================================================

-- DIMENSAO 1: ORGAOS PUBLICOS
CREATE TABLE dim_orgao (
    sk_orgao INTEGER PRIMARY KEY,
    cnpj_orgao VARCHAR(14) NOT NULL UNIQUE,
    nome_orgao VARCHAR(255),
    poder VARCHAR(50)
);


-- DIMENSAO 2: FORNECEDORES
CREATE TABLE dim_fornecedor (
    sk_fornecedor INTEGER PRIMARY KEY,
    ni_fornecedor VARCHAR(30) NOT NULL UNIQUE,
    nome_fornecedor VARCHAR(255),
    tipo_pessoa VARCHAR(50),
    porte VARCHAR(100)
);


-- DIMENSAO 3: MODALIDADES DE CONTRATACAO
CREATE TABLE dim_modalidade (
    sk_modalidade INTEGER PRIMARY KEY,
    modalidade_id INTEGER NOT NULL UNIQUE,
    nome_modalidade VARCHAR(100)
);


-- DIMENSAO 4: LOCALIDADES
CREATE TABLE dim_localidade (
    sk_localidade INTEGER PRIMARY KEY,
    uf_sigla VARCHAR(2) NOT NULL UNIQUE,
    uf_nome VARCHAR(100),
    regiao VARCHAR(30)
);


-- ============================================================
-- TABELA FATO: ITENS CONTRATADOS
-- ============================================================

CREATE TABLE fato_item_contratado (
    sk_fato INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    numero_controle_pncp VARCHAR(100) NOT NULL,
    numero_item INTEGER NOT NULL,

    sk_orgao INTEGER NOT NULL,
    sk_fornecedor INTEGER NOT NULL,
    sk_modalidade INTEGER NOT NULL,
    sk_localidade INTEGER NOT NULL,



    -- DATAS DA CONTRATACAO
    data_publicacao DATE,
    data_homologacao DATE,

    -- IDENTIFICACAO E CLASSIFICACAO DO ITEM
    descricao_item TEXT,
    perfil_gasto VARCHAR(30),

    
    -- QUANTIDADES E VALORES FINANCEIROS
    quantidade DECIMAL(18,4),
    valor_unitario_estimado DECIMAL(18,4),
    valor_total_estimado DECIMAL(18,2),
    valor_unitario_homologado DECIMAL(18,4),
    valor_total_homologado DECIMAL(18,2),


    -- CAMPOS CALCULADOS NO PYTHON
    comparavel SMALLINT,
    economia_valor DECIMAL(18,2),
    dias_ciclo INTEGER,


    -- IMPEDE ITENS DUPLICADOS NA MESMA CONTRATACAO
    CONSTRAINT uq_item_contratado
        UNIQUE (numero_controle_pncp, numero_item),


    -- RELACIONAMENTO COM A DIMENSAO DE ORGAOS
    CONSTRAINT fk_fato_orgao
        FOREIGN KEY (sk_orgao)
        REFERENCES dim_orgao (sk_orgao),


    -- RELACIONAMENTO COM A DIMENSAO DE FORNECEDORES
    CONSTRAINT fk_fato_fornecedor
        FOREIGN KEY (sk_fornecedor)
        REFERENCES dim_fornecedor (sk_fornecedor),


    -- RELACIONAMENTO COM A DIMENSAO DE MODALIDADES
    CONSTRAINT fk_fato_modalidade
        FOREIGN KEY (sk_modalidade)
        REFERENCES dim_modalidade (sk_modalidade),


    -- RELACIONAMENTO COM A DIMENSAO DE LOCALIDADES
    CONSTRAINT fk_fato_localidade
        FOREIGN KEY (sk_localidade)
        REFERENCES dim_localidade (sk_localidade),

    -- IMPEDE QUANTIDADES NULAS, ZERO OU NEGATIVAS
    CONSTRAINT chk_quantidade_positiva
        CHECK (quantidade IS NOT NULL AND quantidade > 0),

    -- IMPEDE VALORES FINANCEIROS NEGATIVOS
    CONSTRAINT chk_valores_nao_negativos
        CHECK (
            valor_unitario_estimado >= 0
            AND valor_total_estimado >= 0
            AND valor_unitario_homologado >= 0
            AND valor_total_homologado >= 0
        )

);
